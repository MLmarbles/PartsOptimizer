import { jsPDF } from 'jspdf';
import type { BuildResponse } from '../types/build';
import type { FpsEstimateData, GameFpsEstimate } from '../types/fps';
import { describeBuild, describeComponent, formatPrice } from './formatting';

export function saveBuildPdf(build: BuildResponse, fpsData: FpsEstimateData | null): void {
    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    const margin = 20;
    const contentWidth = pageWidth - margin * 2;
    let y = margin;

    const addPageIfNeeded = (requiredSpace: number) => {
        if (y + requiredSpace > doc.internal.pageSize.getHeight() - margin) {
            doc.addPage();
            y = margin;
        }
    };

    doc.setFontSize(24);
    doc.setFont('helvetica', 'bold');
    doc.text('PartsOptimizer Build', margin, y);
    y += 8;
    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(120, 120, 120);
    doc.text(new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' }), margin, y);
    y += 4;
    doc.setDrawColor(220, 220, 220);
    doc.line(margin, y, pageWidth - margin, y);
    y += 10;

    doc.setTextColor(100, 100, 100);
    doc.setFontSize(10);
    doc.setFont('helvetica', 'italic');
    const summaryLines = doc.splitTextToSize(describeBuild(build.use_case), contentWidth);
    doc.text(summaryLines, margin, y);
    y += summaryLines.length * 5 + 8;

    doc.setTextColor(0, 0, 0);
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.text('TOTAL PRICE', margin, y);
    doc.text(formatPrice(build.total_price), pageWidth - margin, y, { align: 'right' });
    y += 7;
    doc.setTextColor(160, 160, 160);
    doc.setFont('helvetica', 'normal');
    doc.text('REMAINING BUDGET', margin, y);
    doc.text(formatPrice(build.remaining_budget), pageWidth - margin, y, { align: 'right' });
    y += 6;
    doc.setDrawColor(220, 220, 220);
    doc.line(margin, y, pageWidth - margin, y);
    y += 12;

    doc.setTextColor(120, 120, 120);
    doc.setFontSize(9);
    doc.setFont('helvetica', 'bold');
    doc.text('COMPONENTS', margin, y);
    y += 8;

    build.components.forEach((part) => {
        addPageIfNeeded(35);

        doc.setDrawColor(230, 230, 230);
        doc.setFillColor(250, 250, 250);
        const boxHeight = 28;
        doc.roundedRect(margin, y, contentWidth, boxHeight, 3, 3, 'FD');

        doc.setFontSize(8);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(140, 140, 140);
        let label = part.type.toUpperCase();
        if (part.tier) label += `  •  TIER ${part.tier}`;
        doc.text(label, margin + 6, y + 7);

        doc.setFontSize(10);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(0, 0, 0);
        doc.text(formatPrice(part.price), pageWidth - margin - 6, y + 7, { align: 'right' });

        doc.setFontSize(11);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(0, 0, 0);
        doc.text(part.name, margin + 6, y + 15, { maxWidth: contentWidth - 16 });

        doc.setFontSize(8);
        doc.setFont('helvetica', 'normal');
        doc.setTextColor(130, 130, 130);
        const specText = doc.splitTextToSize(describeComponent(part.type, part.specs, build.use_case), contentWidth - 16);
        doc.text(specText[0] || '', margin + 6, y + 22);

        y += boxHeight + 5;
    });

    if (fpsData && fpsData.estimates && fpsData.estimates.length > 0) {
        y += 5;
        addPageIfNeeded(20);
        doc.setDrawColor(220, 220, 220);
        doc.line(margin, y, pageWidth - margin, y);
        y += 10;

        doc.setTextColor(120, 120, 120);
        doc.setFontSize(9);
        doc.setFont('helvetica', 'bold');
        doc.text('FPS ESTIMATES', margin, y);
        y += 8;

        fpsData.estimates.forEach((est: GameFpsEstimate) => {
            addPageIfNeeded(14);
            doc.setFontSize(10);
            doc.setFont('helvetica', 'bold');
            doc.setTextColor(0, 0, 0);
            doc.text(est.game, margin + 4, y);
            doc.setFont('helvetica', 'normal');
            doc.setTextColor(80, 80, 80);
            const res1080 = est.resolutions.find(r => r.resolution === '1080p');
            const fps = res1080 ? `${res1080.high.min}–${res1080.high.max}` : '—';
            doc.text(`${fps} FPS @ 1080p`, pageWidth - margin, y, { align: 'right' });
            y += 7;
        });
    }

    y += 6;
    addPageIfNeeded(10);
    doc.setDrawColor(220, 220, 220);
    doc.line(margin, y, pageWidth - margin, y);
    y += 8;
    doc.setFontSize(8);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(180, 180, 180);
    doc.text('Generated by PartsOptimizer', margin, y);

    doc.save('PartsOptimizer_Build.pdf');
}
